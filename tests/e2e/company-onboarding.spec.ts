import { expect, test } from "@playwright/test";

test("registers a representative, creates a separate company, and resumes saved onboarding", async ({ page }, testInfo) => {
    test.setTimeout(120000);
    await page.goto("/register?role=recruiter");
    await page.locator('input[name="fullName"]').fill("Đại diện Sao Mai");
    await page.locator('input[name="email"]').fill(`company-${crypto.randomUUID()}@example.com`);
    await page.locator('input[name="phone"]').fill("0912345678");
    await page.locator('input[name="password"]').fill("TalentAI123!");
    await page.locator('input[name="confirmPassword"]').fill("TalentAI123!");
    await page.getByRole("checkbox", { name: /Tôi đồng ý/ }).check();
    await page.getByRole("button", { name: "Hoàn tất", exact: true }).click();
    await expect(page).toHaveURL(/\/recruiter\/onboarding$/, { timeout: 30000 });
    await expect(page.getByRole("heading", { name: "Giới thiệu doanh nghiệp của bạn" })).toBeVisible();
    await expect(page.locator('input[name="name"]')).toHaveValue("");
    await page.getByRole("button", { name: "Tiếp tục", exact: true }).click();
    await expect(page.getByText("Nhập tên công ty có ít nhất 2 ký tự.")).toBeVisible();
    await page.locator('input[name="name"]').fill("Công ty Công nghệ Sao Mai");
    await page.locator('input[name="taxCode"]').fill("0123456789");
    await page.getByRole("combobox", { name: "Lĩnh vực hoạt động chính" }).click();
    await page.getByRole("option").first().click();
    await page.setViewportSize({ width: 1280, height: 960 });
    await page.screenshot({ path: testInfo.outputPath("onboarding-company-desktop.png"), fullPage: true });
    await page.setViewportSize({ width: 375, height: 812 });
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await page.screenshot({ path: testInfo.outputPath("onboarding-company-mobile.png"), fullPage: true });
    await expect(page.locator('input[name="contactEmail"]')).toHaveCount(0);
    await expect(page.locator('input[type="file"]')).toHaveCount(0);
    await page.getByRole("button", { name: "Tiếp tục", exact: true }).click();
    await expect(page.getByRole("heading", { name: "Công ty của bạn ở đâu?" })).toBeVisible();
    await page.getByRole("button", { name: "Tiếp tục", exact: true }).click();
    await expect(page.getByText("Nhập địa chỉ trụ sở công ty.")).toBeVisible();
    await page.locator('input[name="contactPhone"]').fill("0912345678");
    await page.locator('input[name="address"]').fill("12 Đường Hoa, Phường Hải Châu");
    await page.getByRole("combobox", { name: "Tỉnh / Thành phố" }).click();
    await page.getByRole("option", { name: "Đà Nẵng", exact: true }).click();
    await page.getByRole("button", { name: "Quay lại", exact: true }).click();
    await expect(page.locator('input[name="name"]')).toHaveValue("Công ty Công nghệ Sao Mai");
    await page.getByRole("button", { name: "Tiếp tục", exact: true }).click();
    await expect(page.locator('input[name="address"]')).toHaveValue("12 Đường Hoa, Phường Hải Châu");
    await page.screenshot({ path: testInfo.outputPath("onboarding-address-mobile.png"), fullPage: true });
    await page.getByRole("button", { name: "Tiếp tục", exact: true }).click();
    await expect(page.getByRole("heading", { name: "Kiểm tra thông tin công ty" })).toBeVisible();
    await expect(page.locator(".co-review")).toContainText("Công ty Công nghệ Sao Mai");
    await expect(page.locator(".co-review")).toContainText("12 Đường Hoa, Phường Hải Châu");
    await page.screenshot({ path: testInfo.outputPath("onboarding-review-mobile.png"), fullPage: true });
    await page.route("**/api/bff/recruiter/company", async route => {
        if (route.request().method() === "POST") {
            await route.fulfill({ status: 500, json: { error: { code: "INTERNAL_ERROR", message: "INTERNAL_ERROR" } } });
        } else await route.continue();
    });
    await page.getByRole("button", { name: "Tạo hồ sơ công ty", exact: true }).click();
    await expect(page.getByText("Chưa thể lưu thay đổi")).toBeVisible();
    await expect(page.locator(".co-review")).toContainText("Công ty Công nghệ Sao Mai");
    await page.unroute("**/api/bff/recruiter/company");
    await page.getByRole("button", { name: "Tạo hồ sơ công ty", exact: true }).click();
    await expect(page.getByRole("heading", { name: "Hồ sơ công ty đã được tạo!" })).toBeVisible();
    await page.reload();
    await expect(page.getByRole("heading", { name: "Hồ sơ công ty đã được tạo!" })).toBeVisible();
    await page.setViewportSize({ width: 375, height: 812 });
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await page.screenshot({ path: testInfo.outputPath("onboarding-finish-mobile.png"), fullPage: true });
    await expect(page.getByRole("link", { name: /Tạo tin tuyển dụng$/ })).toHaveAttribute("href", "/recruiter/jobs/new");
});
