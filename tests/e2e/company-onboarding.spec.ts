import { expect, test } from "@playwright/test";

test("skips optional information and images without sending invalid or discarded values", async ({ page }, testInfo) => {
    const account = await page.request.post("/api/bff/auth/register", { data: { fullName: "Đại diện kiểm thử bỏ qua", email: `company-skip-${crypto.randomUUID()}@example.com`, password: "TalentAI123!", role: "recruiter", acceptedPrivacyPolicy: true } });
    expect(account.status()).toBe(201);
    await page.goto("/recruiter/onboarding");
    await page.locator('input[name="name"]').fill("Công ty kiểm thử bỏ qua");
    await page.locator('input[name="taxCode"]').fill("0123456789");
    await page.getByLabel("Giới thiệu ngắn về công ty").fill("Doanh nghiệp phát triển phần mềm.");
    await page.getByRole("combobox", { name: "Lĩnh vực hoạt động chính" }).click();
    await page.getByRole("option").first().click();
    await page.getByRole("button", { name: "Tiếp tục", exact: true }).click();
    await page.getByRole("combobox", { name: "Tỉnh / Thành phố" }).click();
    await page.getByRole("option", { name: "Đà Nẵng", exact: true }).click();
    await page.getByLabel("Địa chỉ trụ sở").fill("12 Đường Hoa");
    await page.getByLabel("Số điện thoại liên hệ").fill("0912345678");
    await page.getByRole("button", { name: "Tiếp tục", exact: true }).click();
    await page.getByLabel("Website công ty", { exact: true }).fill("invalid-website");
    await page.getByRole("button", { name: "Tiếp tục", exact: true }).click();
    await expect(page.getByText("Nhập website bắt đầu bằng http:// hoặc https://.", { exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Bỏ qua bước này", exact: true }).click();
    await page.getByLabel("Chọn ảnh đại diện", { exact: true }).setInputFiles({ name: "bad.txt", mimeType: "text/plain", buffer: Buffer.from("bad") });
    await expect(page.getByText("Chọn ảnh PNG, JPG hoặc WebP.", { exact: true })).toBeVisible();
    await page.getByLabel("Chọn ảnh đại diện", { exact: true }).setInputFiles("public/logo/image 1.png");
    await expect(page.getByRole("img", { name: "Ảnh đại diện công ty", exact: true })).toBeVisible();
    await page.getByRole("button", { name: "Bỏ ảnh đại diện", exact: true }).click();
    await expect(page.getByRole("img", { name: "Ảnh đại diện công ty", exact: true })).toHaveCount(0);
    await page.screenshot({ path: testInfo.outputPath("company-preview-placeholder.png"), fullPage: true });
    await page.getByRole("button", { name: "Bỏ qua bước này", exact: true }).click();
    await expect(page.getByRole("heading", { name: "Kiểm tra thông tin công ty" })).toBeVisible();
    await page.getByRole("button", { name: "Tạo hồ sơ công ty", exact: true }).click();
    await expect(page.getByRole("heading", { name: "Hồ sơ công ty đã được tạo!" })).toBeVisible();
    const company = await (await page.request.get("/api/bff/recruiter/company")).json();
    for (const field of ["website", "companySize", "foundedYear", "logoUrl", "coverImageUrl"]) expect(company[field]).toBeUndefined();
});

test("registers a representative, creates a separate company, and resumes saved onboarding", async ({ page }, testInfo) => {
    test.setTimeout(120000);
    await page.goto("/register?role=recruiter");
    await page.locator('input[name="fullName"]').fill("Đại diện Sao Mai");
    await page.locator('input[name="email"]').fill(`company-${crypto.randomUUID()}@example.com`);
    await page.locator('input[name="phone"]').fill("0912345678");
    await page.locator('input[name="password"]').fill("TalentAI123!");
    await page.locator('input[name="confirmPassword"]').fill("TalentAI123!");
    await page.getByRole("checkbox", { name: /Tôi đồng ý/ }).check();
    await page.getByRole("button", { name: "Hoàn tất", exact: true }).click();
    await expect(page).toHaveURL(/\/recruiter\/onboarding$/, { timeout: 30000 });
    await page.goto("/recruiter/dashboard");
    await expect(page).toHaveURL(/\/recruiter\/onboarding$/);
    await expect(page.getByRole("heading", { name: "Giới thiệu doanh nghiệp của bạn" })).toBeVisible();
    await expect(page.locator('input[name="name"]')).toHaveValue("");
    await page.getByRole("button", { name: "Tiếp tục", exact: true }).click();
    await expect(page.getByText("Nhập tên công ty có ít nhất 2 ký tự.")).toBeVisible();
    await expect(page.getByText("Vui lòng nhập mã số thuế công ty.")).toBeVisible();
    await page.locator('input[name="name"]').fill("Công ty Công nghệ Sao Mai");
    await page.locator('input[name="taxCode"]').fill("0123456789");
    await page.getByLabel("Giới thiệu ngắn về công ty").fill("Phát triển phần mềm cho doanh nghiệp.");
    await page.getByRole("combobox", { name: "Lĩnh vực hoạt động chính" }).click();
    await page.getByRole("option").first().click();
    await page.setViewportSize({ width: 1280, height: 960 });
    await page.screenshot({ path: testInfo.outputPath("onboarding-company-desktop.png"), fullPage: true });
    await page.setViewportSize({ width: 375, height: 812 });
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await page.screenshot({ path: testInfo.outputPath("onboarding-company-mobile.png"), fullPage: true });
    await expect(page.locator('input[name="contactEmail"]')).toHaveCount(0);
    await expect(page.locator('input[type="file"]')).toHaveCount(0);
    await page.getByRole("button", { name: "Tiếp tục", exact: true }).click();
    await expect(page.getByRole("heading", { name: "Công ty của bạn ở đâu?" })).toBeVisible();
    await page.getByRole("button", { name: "Tiếp tục", exact: true }).click();
    await expect(page.getByText("Nhập địa chỉ trụ sở công ty.")).toBeVisible();
    await page.locator('input[name="contactPhone"]').fill("0912345678");
    await page.locator('input[name="address"]').fill("12 Đường Hoa, Phường Hải Châu");
    await page.getByRole("combobox", { name: "Tỉnh / Thành phố" }).click();
    await page.getByRole("option", { name: "Đà Nẵng", exact: true }).click();
    await page.getByRole("button", { name: "Quay lại", exact: true }).click();
    await expect(page.locator('input[name="name"]')).toHaveValue("Công ty Công nghệ Sao Mai");
    await page.getByRole("button", { name: "Tiếp tục", exact: true }).click();
    await expect(page.locator('input[name="address"]')).toHaveValue("12 Đường Hoa, Phường Hải Châu");
    await page.screenshot({ path: testInfo.outputPath("onboarding-address-mobile.png"), fullPage: true });
    await page.getByRole("button", { name: "Tiếp tục", exact: true }).click();
    await expect(page.getByRole("heading", { name: "Thêm thông tin cơ bản" })).toBeVisible();
    await page.getByLabel("Website công ty", { exact: true }).fill("https://saomai.example.com");
    await page.getByLabel("Số nhân viên", { exact: true }).fill("50");
    await page.getByLabel("Năm thành lập", { exact: true }).fill("2015");
    await page.getByRole("button", { name: "Tiếp tục", exact: true }).click();
    await expect(page.getByRole("heading", { name: "Tạo dấu ấn cho doanh nghiệp" })).toBeVisible();
    await page.getByLabel("Chọn ảnh đại diện", { exact: true }).setInputFiles("public/logo/image 1.png");
    await expect(page.getByRole("img", { name: "Ảnh đại diện công ty", exact: true })).toBeVisible();
    await page.getByLabel("Chọn ảnh bìa", { exact: true }).setInputFiles("public/images/banner/banner3.png");
    await expect(page.getByRole("img", { name: "Ảnh bìa công ty", exact: true })).toBeVisible();
    await page.screenshot({ path: testInfo.outputPath("onboarding-images-mobile.png"), fullPage: true });
    await page.setViewportSize({ width: 1280, height: 960 });
    await page.screenshot({ path: testInfo.outputPath("onboarding-images-desktop.png"), fullPage: true });
    await page.getByRole("button", { name: "Tiếp tục", exact: true }).click();
    await expect(page.getByRole("heading", { name: "Kiểm tra thông tin công ty" })).toBeVisible();
    await expect(page.locator(".co-review")).toContainText("Công ty Công nghệ Sao Mai");
    await expect(page.locator(".co-review")).toContainText("12 Đường Hoa, Phường Hải Châu");
    await page.screenshot({ path: testInfo.outputPath("onboarding-review-mobile.png"), fullPage: true });
    await page.route("**/api/bff/recruiter/company", async route => {
        if (route.request().method() === "POST") {
            await route.fulfill({ status: 500, json: { error: { code: "INTERNAL_ERROR", message: "INTERNAL_ERROR" } } });
        } else await route.continue();
    });
    await page.getByRole("button", { name: "Tạo hồ sơ công ty", exact: true }).click();
    await expect(page.getByText("Chưa thể lưu thay đổi")).toBeVisible();
    await expect(page.locator(".co-review")).toContainText("Công ty Công nghệ Sao Mai");
    await page.unroute("**/api/bff/recruiter/company");
    let detailWrites = 0;
    page.on("request", request => { if (new URL(request.url()).pathname === "/api/bff/recruiter/company" && ["POST", "PUT"].includes(request.method())) detailWrites++; });
    await page.route("**/api/bff/recruiter/company/cover", route => route.fulfill({ status: 503, json: { error: { code: "SERVICE_UNAVAILABLE" } } }));
    await page.getByRole("button", { name: "Tạo hồ sơ công ty", exact: true }).click();
    await expect(page.getByText("Chưa tải được ảnh công ty", { exact: true })).toBeVisible();
    const partiallySaved = await (await page.request.get("/api/bff/recruiter/company")).json();
    expect(partiallySaved).toMatchObject({ website: "https://saomai.example.com", companySize: 50, foundedYear: 2015 });
    expect(partiallySaved.logoUrl).toBeTruthy();
    expect(partiallySaved.coverImageUrl).toBeUndefined();
    await page.unroute("**/api/bff/recruiter/company/cover");
    await page.getByRole("button", { name: "Thử tải ảnh lại", exact: true }).click();
    await expect(page.getByRole("heading", { name: "Hồ sơ công ty đã được tạo!" })).toBeVisible();
    expect(detailWrites).toBe(1);
    expect((await (await page.request.get("/api/bff/recruiter/company")).json()).coverImageUrl).toBeTruthy();
    await page.reload();
    await expect(page.getByRole("heading", { name: "Hồ sơ công ty đã được tạo!" })).toBeVisible();
    await page.setViewportSize({ width: 375, height: 812 });
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await page.screenshot({ path: testInfo.outputPath("onboarding-finish-mobile.png"), fullPage: true });
    await expect(page.getByRole("link", { name: /Tạo tin tuyển dụng$/ })).toHaveAttribute("href", "/recruiter/jobs/new");
    await page.getByRole("link", { name: "Vào trang quản lý" }).click();
    await expect(page).toHaveURL(/\/recruiter\/dashboard$/);
    const accountMenu = page.getByRole("button", { name: "Menu tài khoản", exact: true });
    const accountNavigation = page.getByRole("navigation", { name: "Menu tài khoản", exact: true });
    await accountMenu.click();
    await expect(accountNavigation.getByRole("link", { name: "Tài khoản", exact: true })).toHaveAttribute("href", "/recruiter/account");
    await expect(accountNavigation.getByRole("link", { name: "Đăng xuất", exact: true })).toBeVisible();
    await page.screenshot({ path: testInfo.outputPath("recruiter-account-menu-mobile.png"), fullPage: true });
    await page.keyboard.press("Escape");
    await expect(accountNavigation).not.toBeVisible();
    await expect(accountMenu).toBeFocused();
    await accountMenu.press("Enter");
    await expect(accountNavigation).toBeVisible();
    await page.getByRole("main").click({ position: { x: 10, y: 10 } });
    await expect(accountNavigation).not.toBeVisible();
    await page.setViewportSize({ width: 1280, height: 960 });
    await accountMenu.click();
    await page.screenshot({ path: testInfo.outputPath("recruiter-account-menu-desktop.png"), fullPage: true });
    await accountNavigation.getByRole("link", { name: "Đăng xuất", exact: true }).click();
    await expect(page).toHaveURL(/\/logout$/);
    await expect(page.getByRole("heading", { name: "Đăng xuất tài khoản" })).toBeVisible();
    await page.getByRole("button", { name: "Đăng xuất", exact: true }).click();
    await expect(page).toHaveURL(/\/login(?:\?reason=logged-out)?$/);
    expect((await page.context().cookies()).filter(cookie => ["access_token", "refresh_token"].includes(cookie.name))).toHaveLength(0);
    await page.goto("/recruiter/dashboard");
    await expect(page).toHaveURL(/\/login$/);
});
