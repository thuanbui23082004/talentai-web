import { expect, test, type Page } from '@playwright/test';
test.setTimeout(90000);
async function login(page: Page) {
  await page.goto('/admin/login');
  await page.getByLabel('Email', { exact: true }).fill('admin@example.test');
  await page.getByLabel('Mật khẩu', { exact: true }).fill('TalentAI2026!');
  await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click();
  await expect(page.locator('.admin-cards')).toBeVisible({ timeout: 20000 });
  await page.goto('/admin/monitoring');
  await expect(page.locator('.admin-monitoring-table tbody tr')).toHaveCount(10);
}
test('system log filters, details, error recovery and mobile layout', async ({ page }, info) => {
  await page.goto('/admin/monitoring'); await expect(page).toHaveURL(/\/admin\/login$/);
  await login(page);
  await page.getByLabel('Mức nhật ký', { exact: true }).selectOption('fatal');
  await expect(page.locator('.admin-monitoring-table tbody tr')).toHaveCount(2);
  await page.getByRole('button', { name: 'Xem chi tiết', exact: true }).first().click();
  await expect(page.getByRole('region', { name: 'Chi tiết nhật ký hệ thống' })).toBeVisible();
  await page.getByLabel('Từ ngày', { exact: true }).fill('2026-11-07');
  await page.getByLabel('Đến ngày', { exact: true }).fill('2026-10-01');
  await expect(page.locator('.admin-main [role=alert]:visible')).toContainText('Ngày kết thúc');
  await page.getByRole('button', { name: 'Xóa bộ lọc', exact: true }).click();
  await page.getByLabel('Tìm kiếm', { exact: true }).fill('khong-co-ban-ghi');
  await expect(page.getByText('Không có bản ghi phù hợp.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Xóa bộ lọc', exact: true }).click();
  await page.route('**/api/bff/admin/system-logs?*', route => route.fulfill({ status: 500, json: { error: { code: 'INTERNAL_ERROR' } } }));
  await page.getByRole('button', { name: 'Làm mới', exact: true }).click();
  await expect(page.locator('.admin-state[role=alert]')).toBeVisible();
  await page.unroute('**/api/bff/admin/system-logs?*');
  await page.getByRole('button', { name: 'Thử lại', exact: true }).click();
  await expect(page.locator('.admin-monitoring-table tbody tr')).toHaveCount(10);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: info.outputPath('monitoring-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 360, height: 800 });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(360);
  await page.screenshot({ path: info.outputPath('monitoring-mobile.png'), fullPage: true });
});
test('anomaly review requires note and confirmation, retries and persists with audit', async ({ page }, info) => {
  await login(page);
  await page.getByRole('button', { name: 'Hoạt động bất thường', exact: true }).click();
  await page.getByLabel('Trạng thái', { exact: true }).filter({ visible: true }).selectOption('open');
  await page.getByRole('button', { name: 'Xem chi tiết', exact: true }).first().click();
  const detail = page.getByRole('region', { name: 'Chi tiết hoạt động bất thường', exact: true });
  await detail.getByRole('button', { name: 'Tiếp tục', exact: true }).click();
  await expect(detail.getByRole('alert')).toContainText('Vui lòng nhập ghi chú');
  const note = 'Đã kiểm tra bối cảnh hoạt động trong phiên kiểm thử.';
  await detail.getByLabel('Ghi chú / lý do xem xét', { exact: true }).fill(note);
  await detail.getByRole('button', { name: 'Tiếp tục', exact: true }).click();
  await page.route('**/api/bff/admin/anomalies/*', route => route.fulfill({ status: 500, json: { error: { code: 'INTERNAL_ERROR' } } }));
  await detail.getByRole('button', { name: 'Xác nhận kết quả', exact: true }).click();
  await expect(detail.getByRole('alert')).toContainText('Không thể cập nhật');
  await expect(detail.getByRole('region', { name: 'Xác nhận kết quả' })).toContainText(note);
  await page.unroute('**/api/bff/admin/anomalies/*');
  await detail.getByRole('button', { name: 'Xác nhận kết quả', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Đã ghi nhận kết quả');
  await expect(detail).toContainText('Cảnh báo đã có kết quả xem xét.');
  await expect(page.locator('.admin-monitoring-table tbody tr')).toHaveCount(9);
  await page.setViewportSize({ width: 360, height: 800 });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(360);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: info.outputPath('monitoring-review-mobile.png'), fullPage: true });
  await page.reload();
  await page.getByRole('button', { name: 'Hoạt động bất thường', exact: true }).click();
  await page.getByLabel('Trạng thái', { exact: true }).filter({ visible: true }).selectOption('reviewed');
  await page.getByRole('button', { name: 'Xem chi tiết', exact: true }).first().click();
  await expect(detail).toContainText(note);
  await page.goto('/admin/activity-logs');
  await page.getByLabel('Hành động', { exact: true }).filter({ visible: true }).selectOption('anomaly.review');
  await expect(page.locator('.admin-activity-table:visible tbody tr')).toHaveCount(1);
  await page.getByRole('button', { name: 'Xem chi tiết', exact: true }).click();
  await expect(page.locator('.admin-activity-detail')).toContainText(note);
});
