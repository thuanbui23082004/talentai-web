import { test, expect } from '@playwright/test';
import type { components } from '@/lib/api/generated/schema';
import example from '../../contracts/examples/job-applicants.json';
import { mockJobs } from '@/mocks/fixtures/recruiter-jobs';

test('job-scoped board loads all pages, saves drag status/version, handles conflicts and changes jobs', async ({ page }, info) => {
    test.setTimeout(180000);
    const registered = await page.request.post('/api/bff/auth/register', { data: { email: `pipeline-ui-${crypto.randomUUID()}@example.com`, password: 'TalentAI123!', fullName: 'Recruiter Pipeline Test', role: 'recruiter' } });
    expect(registered.status()).toBe(201);
    const { csrfToken } = await registered.json();
    const catalogs = await (await page.request.get('/api/bff/recruiter/company/catalogs')).json();
    expect((await page.request.post('/api/bff/recruiter/company', { headers: { 'X-CSRF-Token': csrfToken }, data: { name: 'Pipeline UI Test', taxCode: String(Date.now()).slice(-10), description: 'Isolated pipeline UI test company.', industryIds: [catalogs.industries[0].id], city: catalogs.locations[0].name } })).status()).toBe(201);
    const first: components['schemas']['JobApplicant'] = { ...example.items[0], status: 'submitted', version: 0 };
    const second = { ...first, id: 'b0000000-0000-4000-8000-000000000002', fullName: 'Ứng viên trang hai', status: 'reviewing' as const };
    const otherJob = '10000000-0000-4000-8000-000000000099';
    const reads: URL[] = [];
    const writes: unknown[] = [];
    let conflict = false;
    let unavailable = false;
    await page.route('**/api/bff/recruiter/jobs**', route => {
        const url = new URL(route.request().url());
        if (url.pathname.endsWith('/applications')) {
            reads.push(url);
            if (unavailable) return route.fulfill({ status: 503, json: { error: { code: 'SERVICE_UNAVAILABLE' } } });
            const other = url.pathname.includes(otherJob);
            const items = other ? [] : [url.searchParams.get('page') === '2' ? second : first];
            return route.fulfill({ json: { items, meta: { page: Number(url.searchParams.get('page')), pageSize: 100, totalItems: other ? 0 : 2, totalPages: other ? 0 : 2 } } });
        }
        return route.fulfill({ json: { items: [{ ...mockJobs[0], id: first.jobId, title: 'React Developer' }, { ...mockJobs[0], id: otherJob, title: 'Backend Developer' }], meta: { page: 1, pageSize: 100, totalItems: 2, totalPages: 1 } } });
    });
    await page.route(`**/api/bff/recruiter/job-applications/${first.id}/status`, async route => {
        const values = route.request().postDataJSON();
        writes.push(values);
        if (conflict) return route.fulfill({ status: 409, json: { error: { code: 'CONFLICT' } } });
        first.status = values.status;
        first.version++;
        await route.fulfill({ json: first });
    });
    await page.goto('/recruiter/candidates/pipeline');
    await expect(page.getByText('Vui lòng chọn tin tuyển dụng để xem bảng theo dõi ứng viên.', { exact: true })).toBeVisible();
    expect(reads).toHaveLength(0);
    await page.getByRole('combobox', { name: 'Tin tuyển dụng', exact: true }).click();
    await page.getByRole('option', { name: 'React Developer', exact: true }).click();
    const card = page.locator(`.pipeline-card[data-application-id="${first.id}"]`);
    await expect(card).toBeVisible();
    await expect(page.getByRole('link', { name: second.fullName, exact: true })).toBeVisible();
    expect(reads.some(url => url.searchParams.get('page') === '2')).toBe(true);
    const grip = card.getByRole('button', { name: `Kéo thẻ của ${first.fullName}`, exact: true });
    await expect(grip).toBeEnabled();
    const source = await grip.boundingBox();
    const target = await page.locator('[data-stage="reviewing"] .pipeline-column-heading').boundingBox();
    await page.mouse.move(source!.x + source!.width / 2, source!.y + source!.height / 2);
    await page.mouse.down();
    await page.mouse.move(source!.x + source!.width / 2 + 10, source!.y + 10, { steps: 3 });
    await page.mouse.move(target!.x + target!.width / 2, target!.y + 20, { steps: 20 });
    await page.mouse.up();
    await expect(page.locator('[data-stage="reviewing"]').locator(card)).toBeVisible();
    expect(writes).toEqual([{ status: 'reviewing', version: 0 }]);
    conflict = true;
    const move = card.getByRole('combobox', { name: `Chuyển trạng thái của ${first.fullName}`, exact: true });
    await expect(move).toBeEnabled();
    await move.click();
    await page.getByRole('option', { name: 'Đã chọn vào danh sách ngắn', exact: true }).click();
    await expect(page.getByRole('alert').filter({ hasText: 'Hồ sơ đã thay đổi' })).toBeVisible();
    expect(writes.at(-1)).toEqual({ status: 'shortlisted', version: 1 });
    await expect(page.locator('[data-stage="reviewing"]').locator(card)).toBeVisible();
    await page.screenshot({ path: info.outputPath('pipeline-desktop.png'), fullPage: true });
    await page.getByRole('combobox', { name: 'Tin tuyển dụng', exact: true }).click();
    await page.getByRole('option', { name: 'Backend Developer', exact: true }).click();
    await expect(page).toHaveURL(new RegExp(`jobId=${otherJob}`));
    await expect(page.getByText('Chưa có ứng viên ứng tuyển vào tin này.', { exact: true })).toBeVisible();
    await expect(card).toHaveCount(0);
    await page.setViewportSize({ width: 375, height: 900 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: info.outputPath('pipeline-mobile.png'), fullPage: true });
    unavailable = true;
    await page.reload();
    await expect(page.getByRole('alert').filter({ hasText: 'Không tải được hồ sơ' })).toBeVisible();
    unavailable = false;
    await page.getByRole('button', { name: 'Thử lại', exact: true }).click();
    await expect(page.getByText('Chưa có ứng viên ứng tuyển vào tin này.', { exact: true })).toBeVisible();
});
