import { expect, test, type Page } from '@playwright/test';
test.setTimeout(120000);
async function login(page: Page) {
  await page.goto('/admin/login');
  await page.getByLabel('Email', { exact: true }).fill('admin@example.test');
  await page.getByLabel('Mật khẩu', { exact: true }).fill('TalentAI2026!');
  const response = page.waitForResponse(value => value.url().includes('/api/bff/auth/login') && value.request().method() === 'POST');
  await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click();
  const loginResponse = await response;
  expect(loginResponse.request().headers()['x-talentai-workspace']).toBe('admin');
  expect(loginResponse.status()).toBe(200);
  await expect(page.locator('.admin-cards')).toBeVisible({ timeout: 30000 });
  await page.getByRole('button', { name: 'Hệ thống', exact: true }).click();
  await page.getByRole('tab', { name: 'Thống kê và báo cáo', exact: true }).click();
  await expect(page).toHaveURL(/\/admin\/statistics$/);
  await expect(page.getByRole('region', { name: 'Thống kê hồ sơ ứng tuyển', exact: true })).toContainText('591', { timeout: 30000 });
}
test('statistics navigation, date filters, interval totals, accessible table and responsive layout', async ({ page }, info) => {
  await page.goto('/admin/statistics'); await expect(page).toHaveURL(/\/admin\/login$/);
  await login(page);
  await expect(page.getByRole('tab', { name: 'Thống kê và báo cáo', exact: true })).toHaveAttribute('aria-selected', 'true');
  const trend = page.getByRole('region', { name: 'Xu hướng hoạt động', exact: true });
  await trend.getByText('Xem bảng số liệu biểu đồ', { exact: true }).click();
  await expect(trend.locator('tbody tr')).toHaveCount(5);
  await page.getByLabel('Từ ngày', { exact: true }).fill('2026-11-02');
  await page.getByLabel('Đến ngày', { exact: true }).fill('2026-11-04');
  await page.getByRole('button', { name: 'Áp dụng', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Thống kê hồ sơ ứng tuyển', exact: true })).toContainText('367');
  await page.getByLabel('Nhóm thời gian', { exact: true }).selectOption('week');
  await expect(trend.locator('tbody tr')).toHaveCount(1);
  await expect(trend.locator('tbody')).toContainText('367');
  await page.getByLabel('Chỉ số biểu đồ', { exact: true }).selectOption('new_companies');
  await expect(trend.locator('tbody')).toContainText('15');
  await page.getByLabel('Từ ngày', { exact: true }).fill('2026-11-07');
  await expect(page.getByRole('button', { name: 'Áp dụng', exact: true })).toBeDisabled();
  await expect(page.locator('#statistics-date-error')).toContainText('Ngày kết thúc');
  await page.getByRole('button', { name: 'Toàn bộ thời gian', exact: true }).click();
  await expect(page.getByLabel('Từ ngày', { exact: true })).toHaveValue('');
  await expect(page.getByLabel('Đến ngày', { exact: true })).toHaveValue('');
  await expect(page.locator('#statistics-date-error')).toHaveCount(0);
  await expect(page.getByRole('region', { name: 'Thống kê hồ sơ ứng tuyển', exact: true })).toContainText('591');
  await page.getByLabel('Chỉ số biểu đồ', { exact: true }).selectOption('applications');
  await page.getByLabel('Nhóm thời gian', { exact: true }).selectOption('day');
  await expect(trend.locator('tbody tr')).toHaveCount(5);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.addStyleTag({ content: 'nextjs-portal { display: none !important; }' });
  await page.screenshot({ path: info.outputPath('statistics-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 375, height: 812 });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(375);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: info.outputPath('statistics-mobile.png'), fullPage: true });
  await page.reload(); await expect(page.getByRole('heading', { name: 'Thống kê và báo cáo', exact: true })).toBeVisible();
});
test('statistics loading, partial errors, retry, empty period and expired session', async ({ page, context }) => {
  await login(page);
  await page.route('**/api/bff/admin/stats/applications*', async route => { await new Promise(resolve => setTimeout(resolve, 700)); await route.fulfill({ status: 500, json: { error: { code: 'INTERNAL_ERROR', message: 'private upstream error' } } }); });
  await page.getByRole('button', { name: 'Làm mới', exact: true }).click();
  const app = page.getByRole('region', { name: 'Thống kê hồ sơ ứng tuyển', exact: true });
  await expect(app.getByRole('alert')).toContainText('Không thể tải số liệu');
  await expect(page.getByText('private upstream error')).toHaveCount(0);
  await expect(page.getByRole('region', { name: 'Chỉ số hoạt động hệ thống', exact: true })).toContainText('240');
  await page.unroute('**/api/bff/admin/stats/applications*');
  await app.getByRole('button', { name: 'Thử lại', exact: true }).click();
  await expect(app).toContainText('591');
  await page.route('**/api/bff/admin/stats/timeseries*', async route => { await new Promise(resolve => setTimeout(resolve, 1200)); await route.continue(); });
  await page.getByLabel('Chỉ số biểu đồ', { exact: true }).selectOption('ai_tasks');
  await expect(page.getByRole('region', { name: 'Xu hướng hoạt động', exact: true }).locator('[aria-busy=true]')).toBeVisible();
  await page.unroute('**/api/bff/admin/stats/timeseries*');
  await page.getByLabel('Từ ngày', { exact: true }).fill('2099-01-01');
  await page.getByRole('button', { name: 'Áp dụng', exact: true }).click();
  await expect(app).toContainText('Không có số liệu');
  await expect(page.getByRole('region', { name: 'Xu hướng hoạt động', exact: true })).toContainText('Không có số liệu');
  await context.clearCookies();
  await page.getByRole('button', { name: 'Làm mới', exact: true }).click();
  await expect(app.getByRole('alert')).toContainText('Phiên quản trị không còn hợp lệ');
  await expect(app.getByRole('link', { name: 'Đăng nhập admin', exact: true })).toBeVisible();
});
