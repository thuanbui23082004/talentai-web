import { expect, test, type Page } from '@playwright/test';
test.setTimeout(90000);
async function login(page: Page) {
  await page.goto('/admin/login');
  await page.getByLabel('Email', { exact: true }).fill('admin@example.test');
  await page.getByLabel('Mật khẩu', { exact: true }).fill('TalentAI2026!');
  await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click();
  await expect(page).toHaveURL(/\/admin\/dashboard$/);
  await page.goto('/admin/users');
  await expect(page.locator('.admin-users-table')).toBeVisible();
  await page.addStyleTag({ content: 'nextjs-portal { display: none !important; }' });
}
test('search, filter, detail, lock/unlock, audit and mobile', async ({ page }, info) => {
  await page.goto('/admin/users');
  await expect(page).toHaveURL(/\/admin\/login$/);
  await login(page);
  await page.getByRole('button', { name: 'Trang sau', exact: true }).click();
  await expect(page.getByText('Trang 2 / 2', { exact: true })).toBeVisible();
  await page.getByLabel('Tìm kiếm người dùng', { exact: true }).fill('user3@example.test');
  await page.getByLabel('Vai trò', { exact: true }).selectOption('candidate');
  await expect(page.locator('.admin-users-table tbody tr')).toHaveCount(1);
  expect(page.url()).not.toContain('example');
  await page.screenshot({ path: info.outputPath('users-desktop.png'), fullPage: true });
  await page.getByRole('link', { name: 'Xem chi tiết', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Chi tiết tài khoản', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Khóa tài khoản', exact: true }).click();
  await page.getByRole('button', { name: 'Tiếp tục', exact: true }).click();
  await expect(page.getByText('Vui lòng nhập lý do.', { exact: true })).toBeVisible();
  await page.getByLabel('Lý do', { exact: true }).fill('Kiểm tra khóa tài khoản mẫu');
  await page.getByRole('button', { name: 'Tiếp tục', exact: true }).click();
  await page.getByRole('button', { name: 'Xác nhận khóa', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Đã khóa tài khoản');
  await expect(page.locator('.admin-user-history')).toContainText('Kiểm tra khóa tài khoản mẫu');
  await page.reload();
  await expect(page.getByRole('button', { name: 'Mở khóa tài khoản', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Mở khóa tài khoản', exact: true }).click();
  await page.getByLabel('Lý do', { exact: true }).fill('Đã xác minh lại thông tin mẫu');
  await page.getByRole('button', { name: 'Tiếp tục', exact: true }).click();
  await page.getByRole('button', { name: 'Xác nhận mở khóa', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Đã mở khóa tài khoản');
  await page.setViewportSize({ width: 360, height: 800 });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(360);
  await page.addStyleTag({ content: 'nextjs-portal { display: none !important; }' });
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: info.outputPath('user-detail-mobile.png'), fullPage: true });
  await page.getByRole('link', { name: 'Về danh sách', exact: true }).click();
  await page.getByLabel('Tìm kiếm người dùng', { exact: true }).fill('user3@example.test');
  await expect(page.locator('.admin-users-table tbody')).toContainText('Đang hoạt động');
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(360);
  await page.addStyleTag({ content: 'nextjs-portal { display: none !important; }' });
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: info.outputPath('users-mobile.png'), fullPage: true });
  await page.goto('/admin/dashboard');
  await expect(page.locator('.admin-activity tbody tr').first()).toContainText('Mở khóa tài khoản');
});
test('empty, retry and rejected mutation preserve the reason', async ({ page }) => {
  await login(page);
  await page.getByLabel('Tìm kiếm người dùng', { exact: true }).fill('khong-co-nguoi-dung');
  await expect(page.getByText('Không tìm thấy tài khoản phù hợp.', { exact: true })).toBeVisible();
  await page.route('**/api/bff/admin/users?*', route => route.fulfill({ status: 500, json: { error: { code: 'INTERNAL_ERROR' } } }));
  await page.getByRole('button', { name: 'Làm mới', exact: true }).click();
  await expect(page.locator('.admin-state[role=alert]')).toContainText('Không thể tải dữ liệu');
  await page.unroute('**/api/bff/admin/users?*');
  await page.getByRole('button', { name: 'Thử lại', exact: true }).click();
  await page.getByLabel('Tìm kiếm người dùng', { exact: true }).fill('user6@example.test');
  await page.getByRole('link', { name: 'Xem chi tiết', exact: true }).click();
  await page.getByRole('button', { name: 'Khóa tài khoản', exact: true }).click();
  await page.getByLabel('Lý do', { exact: true }).fill('Giữ lại nội dung khi lỗi');
  await page.getByRole('button', { name: 'Tiếp tục', exact: true }).click();
  await page.route('**/api/bff/admin/users/*/lock', route => route.fulfill({ status: 500, json: { error: { code: 'INTERNAL_ERROR' } } }));
  await page.getByRole('button', { name: 'Xác nhận khóa', exact: true }).click();
  await expect(page.locator('.admin-access-panel [role=alert]')).toContainText('Không thể cập nhật');
  await page.getByRole('button', { name: 'Sửa lý do', exact: true }).click();
  await expect(page.getByLabel('Lý do', { exact: true })).toHaveValue('Giữ lại nội dung khi lỗi');
});

