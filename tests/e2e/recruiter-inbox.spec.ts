import { expect, test } from './recruiter-fixture';

test('inbox supports search, starring, replies, drafts and restoring deleted mail', async ({ page }) => {
  await page.goto('/recruiter/inbox');
  await expect(page.getByRole('heading', { name: 'Hộp thư', exact: true })).toBeVisible();
  await page.getByRole('searchbox', { name: 'Tìm kiếm thư' }).fill('Hà Linh');
  await expect(page.locator('.mail-row')).toHaveCount(1);
  await page.locator('.mail-row-main').click();
  await expect(page.locator('.mail-content h2')).toHaveText('Xác nhận lịch phỏng vấn Frontend Developer');
  await page.locator('.mail-content').getByRole('button', { name: 'Trả lời', exact: true }).click();
  await expect(page.getByLabel('Người nhận', { exact: true })).toHaveValue('ha.linh@example.com');
  await page.getByRole('button', { name: 'Gửi', exact: true }).click();
  await expect(page.locator('.mail-composer [role=alert]')).toBeVisible();
  await page.getByRole('textbox', { name: 'Nội dung', exact: true }).fill('Cảm ơn bạn đã xác nhận. Hẹn gặp bạn tại buổi phỏng vấn.');
  await page.getByRole('button', { name: 'Gửi', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Không có email thật được gửi');
  await expect(page.locator('.mail-content h2')).toContainText('Trả lời:');
  await page.getByRole('button', { name: 'Chuyển vào thùng rác', exact: true }).click();
  await page.getByRole('button', { name: 'Thùng rác', exact: true }).click();
  await page.locator('.mail-row-main').click();
  await page.getByRole('button', { name: 'Khôi phục về hộp thư đến', exact: true }).click();
  await page.getByRole('button', { name: 'Hộp thư đến', exact: false }).click();
  await page.locator('.mail-row').filter({ hasText: 'Trả lời:' }).getByRole('button', { name: 'Gắn sao', exact: true }).click();
  await page.getByRole('button', { name: 'Có gắn sao', exact: true }).click();
  await expect(page.locator('.mail-row').filter({ hasText: 'Trả lời:' })).toBeVisible();
  await page.getByRole('button', { name: 'Soạn thư', exact: true }).click();
  await page.getByLabel('Tiêu đề', { exact: true }).fill('Thư nháp thử nghiệm');
  await page.getByRole('button', { name: 'Lưu nháp', exact: true }).click();
  await page.locator('.mail-row-main').click();
  await expect(page.getByLabel('Tiêu đề', { exact: true })).toHaveValue('Thư nháp thử nghiệm');
});

