import { expect, test } from './recruiter-fixture';
import { catalogPageSchema } from '@/lib/api/job-schemas';

test('form reuses shared dropdowns, calendar and searchable province/ward popup', async ({ page }, info) => {
  await page.goto('/recruiter/jobs/new');
  const city = page.locator('#job-city');
  await expect(city).toBeVisible();
  const catalog = catalogPageSchema.parse(await (await page.request.get('/api/bff/catalog/locations?pageSize=100')).json());
  expect(catalog.items).toHaveLength(34);
  const filtered = catalogPageSchema.parse(await (await page.request.get('/api/bff/catalog/locations?q=can%20tho&pageSize=100')).json());
  expect(filtered.items.map(item => item.name)).toEqual(['Cần Thơ']);
  await page.locator('#job-experienceLevel').click();
  await page.getByRole('option', { name: 'Chuyên gia', exact: true }).click();
  await expect(page.locator('#job-experienceLevel')).toContainText('Chuyên gia');
  await page.locator('#job-applicationDeadline').click();
  await expect(page.getByRole('group', { name: 'Danh sách ngày', exact: true })).toBeVisible();
  await page.getByRole('group', { name: 'Danh sách ngày', exact: true }).getByRole('button').nth(10).click();
  await expect(page.locator('#job-applicationDeadline')).not.toContainText('Chọn ngày / tháng / năm');
  await page.locator('#job-applicationDeadline').click();
  await page.keyboard.press('Escape');
  await city.click();
  const dialog = page.getByRole('dialog');
  await dialog.getByRole('searchbox', { name: 'Tìm tỉnh thành' }).fill('ha noi');
  await dialog.getByRole('button', { name: 'Hà Nội', exact: true }).click();
  const ward = dialog.locator('[aria-label="Danh sách phường xã"] button').nth(1);
  const wardName = (await ward.innerText()).trim();
  await ward.click();
  await page.screenshot({ path: info.outputPath('location-search-desktop.png') });
  await dialog.getByRole('button', { name: 'Chọn địa điểm', exact: true }).click();
  await expect(city).toContainText(wardName);
  await expect(page.locator('.create-job-preview')).toContainText(wardName);
  await city.click();
  await dialog.getByRole('searchbox', { name: 'Tìm tỉnh thành' }).fill('khong-co-dia-diem');
  await expect(dialog.getByText('Không tìm thấy tỉnh/thành.', { exact: true })).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(city).toContainText(wardName);
});

test('job filters use the same searchable catalog, clear selection and retry API errors', async ({ page }) => {
  await page.route('**/api/bff/catalog/locations?*', route => route.fulfill({ status: 500, contentType: 'application/problem+json', body: JSON.stringify({ error: { code: 'INTERNAL_ERROR' } }) }));
  await page.goto('/recruiter/jobs');
  const city = page.getByRole('combobox', { name: 'Địa điểm', exact: true });
  await city.click();
  await expect(page.getByRole('alert')).toContainText('Không thể tải địa điểm.');
  await page.unroute('**/api/bff/catalog/locations?*');
  await page.getByRole('button', { name: 'Thử lại', exact: true }).click();
  await city.fill('ha noi');
  await page.getByRole('option', { name: 'Hà Nội', exact: true }).click();
  await expect(city).toHaveValue('Hà Nội');
  await expect(page.locator('.job-card').first()).toBeVisible();
  for (const text of await page.locator('.job-card-meta').allTextContents()) expect(text).toContain('Hà Nội');
  await page.getByRole('button', { name: 'Xóa lọc', exact: true }).first().click();
  await expect(city).toHaveValue('');
  await city.click();
  await city.fill('can tho');
  await page.getByRole('option', { name: 'Cần Thơ', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Không tìm thấy tin tuyển dụng', exact: true })).toBeVisible();
});

test('edit selection stays populated and mobile popup fits the screen', async ({ page }, info) => {
  await page.goto('/recruiter/jobs');
  const link = page.locator('.detail-card-link').first();
  await expect(link).toBeVisible();
  const href = await link.getAttribute('href');
  await page.goto(`${href}/edit`);
  const city = page.locator('#job-city');
  const original = await city.innerText();
  await city.click();
  await page.getByRole('searchbox', { name: 'Tìm tỉnh thành' }).fill('khong-khop');
  await page.keyboard.press('Escape');
  await expect(city).toHaveText(original);
  await page.setViewportSize({ width: 375, height: 900 });
  await city.click();
  await page.getByRole('searchbox', { name: 'Tìm tỉnh thành' }).fill('ninh');
  await expect(page.getByRole('dialog').getByRole('button', { name: 'Ninh Bình', exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  const popup = await page.getByRole('dialog').boundingBox();
  expect(popup!.x).toBeGreaterThanOrEqual(0);
  expect(popup!.x + popup!.width).toBeLessThanOrEqual(375);
  await page.screenshot({ path: info.outputPath('location-search-mobile.png') });
  await page.getByRole('dialog').getByRole('button', { name: 'Ninh Bình', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Chọn địa điểm', exact: true }).click();
  await expect(city).toContainText('Ninh Bình');
});
