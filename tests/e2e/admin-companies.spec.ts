import { expect, test, type Page } from '@playwright/test';
test.setTimeout(90000);
async function login(page: Page) {
  await page.goto('/admin/login');
  await page.getByLabel('Email', { exact: true }).fill('admin@example.test');
  await page.getByLabel('Mật khẩu', { exact: true }).fill('TalentAI2026!');
  await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click();
  await expect(page.locator('.admin-cards')).toBeVisible({ timeout: 20000 });
  await page.addStyleTag({ content: 'nextjs-portal { display: none !important; }' });
}
async function confirmAction(page: Page, name: string, reason: string) {
  await page.getByRole('button', { name, exact: true }).click();
  await page.getByLabel('Ghi chú / lý do xử lý', { exact: true }).fill(reason);
  await page.getByRole('button', { name: 'Tiếp tục', exact: true }).click();
  await page.getByRole('button', { name: 'Xác nhận', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Đã cập nhật trạng thái doanh nghiệp');
}
test('company list, document preview/download, verification, suspension and restoration', async ({ page }, info) => {
  await page.goto('/admin/companies'); await expect(page).toHaveURL(/\/admin\/login$/);
  await login(page);
  const before = Number(await page.locator('.admin-card').nth(2).locator('strong').innerText());
  await page.getByRole('button', { name: 'Tài khoản', exact: true }).click();
  await page.getByRole('tab', { name: 'Doanh nghiệp', exact: true }).click();
  await expect(page).toHaveURL(/\/admin\/companies$/);
  await expect(page.locator('.admin-companies-table')).toBeVisible();
  await page.getByRole('button', { name: 'Trang sau', exact: true }).click();
  await expect(page.getByText('Trang 2 / 2', { exact: true })).toBeVisible();
  await page.getByLabel('Tìm kiếm doanh nghiệp', { exact: true }).fill('0000000001');
  await page.getByLabel('Trạng thái xác minh', { exact: true }).selectOption('pending');
  await expect(page.locator('.admin-companies-table tbody tr')).toHaveCount(1);
  await page.screenshot({ path: info.outputPath('companies-desktop.png'), fullPage: true });
  await page.getByRole('link', { name: 'Xem chi tiết', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Chi tiết doanh nghiệp', exact: true })).toBeVisible();
  await page.getByRole('button', { name: /^Xem giấy tờ/ }).click();
  await expect(page.getByTitle('Nội dung giấy tờ xác minh')).toHaveAttribute('src', /^blob:/);
  const download = page.waitForEvent('download'); await page.getByRole('link', { name: 'Tải giấy tờ', exact: true }).click();
  expect((await download).suggestedFilename()).toMatch(/\.pdf$/);
  await page.getByRole('button', { name: 'Đóng giấy tờ', exact: true }).click();
  await page.getByRole('button', { name: 'Duyệt xác minh', exact: true }).click();
  await page.getByRole('button', { name: 'Tiếp tục', exact: true }).click();
  await expect(page.getByText('Vui lòng nhập ghi chú hoặc lý do.', { exact: true })).toBeVisible();
  await page.getByLabel('Ghi chú / lý do xử lý', { exact: true }).fill('Đã đối chiếu hồ sơ giả lập');
  await page.getByRole('button', { name: 'Tiếp tục', exact: true }).click();
  await page.screenshot({ path: info.outputPath('company-confirm-desktop.png'), fullPage: true });
  await page.getByRole('button', { name: 'Xác nhận', exact: true }).click();
  await expect(page.locator('.admin-users-heading .admin-badge')).toHaveText('Đã xác minh');
  await confirmAction(page, 'Đình chỉ doanh nghiệp', 'Kiểm tra vi phạm mẫu');
  await expect(page.locator('.admin-users-heading .admin-badge')).toHaveText('Đang đình chỉ');
  await confirmAction(page, 'Khôi phục doanh nghiệp', 'Đã kiểm tra và gỡ đình chỉ');
  await expect(page.locator('.admin-users-heading .admin-badge')).toHaveText('Đã xác minh');
  await expect(page.locator('.admin-user-history li')).toHaveCount(3);
  await page.reload(); await expect(page.locator('.admin-users-heading .admin-badge')).toHaveText('Đã xác minh');
  await page.setViewportSize({ width: 360, height: 800 });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(360);
  await page.addStyleTag({ content: 'nextjs-portal { display: none !important; }' }); await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: info.outputPath('company-detail-mobile.png'), fullPage: true });
  await page.getByRole('link', { name: 'Về danh sách doanh nghiệp', exact: true }).click();
  await page.getByLabel('Tìm kiếm doanh nghiệp', { exact: true }).fill('0000000001');
  await expect(page.locator('.admin-companies-table tbody')).toContainText('Đã xác minh');
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(360);
  await page.evaluate(() => window.scrollTo(0, 0)); await page.screenshot({ path: info.outputPath('companies-mobile.png'), fullPage: true });
  await page.goto('/admin/dashboard');
  await expect(page.locator('.admin-card').nth(2).locator('strong')).toHaveText(String(before - 1));
  await expect(page.locator('.admin-activity tbody tr').first()).toContainText('Khôi phục doanh nghiệp');
});
test('empty search, API retry, document failure and rejection with preserved reason', async ({ page }) => {
  await login(page); await page.goto('/admin/companies');
  await expect(page.locator('.admin-companies-table')).toBeVisible();
  await page.getByLabel('Tìm kiếm doanh nghiệp', { exact: true }).fill('khong-co-doanh-nghiep');
  await expect(page.getByText('Không tìm thấy doanh nghiệp phù hợp.', { exact: true })).toBeVisible();
  await page.route('**/api/bff/admin/companies?*', route => route.fulfill({ status: 500, json: { error: { code: 'INTERNAL_ERROR' } } }));
  await page.getByRole('button', { name: 'Làm mới', exact: true }).click();
  await expect(page.locator('.admin-state[role=alert]')).toContainText('Không thể tải dữ liệu doanh nghiệp');
  await page.unroute('**/api/bff/admin/companies?*'); await page.getByRole('button', { name: 'Thử lại', exact: true }).click();
  await page.getByLabel('Tìm kiếm doanh nghiệp', { exact: true }).fill('0000000006');
  await page.getByRole('link', { name: 'Xem chi tiết', exact: true }).click();
  await page.route('**/api/bff/admin/companies/*/documents/*', route => route.fulfill({ status: 500, json: { error: { code: 'INTERNAL_ERROR' } } }));
  await page.getByRole('button', { name: /^Xem giấy tờ/ }).click();
  await expect(page.locator('.admin-company-preview [role=alert]')).toContainText('Không thể mở giấy tờ');
  await page.unroute('**/api/bff/admin/companies/*/documents/*'); await page.getByRole('button', { name: 'Thử lại', exact: true }).click();
  await expect(page.getByTitle('Nội dung giấy tờ xác minh')).toHaveAttribute('src', /^blob:/);
  await page.getByRole('button', { name: 'Đóng giấy tờ', exact: true }).click();
  await page.getByRole('button', { name: 'Từ chối xác minh', exact: true }).click();
  await page.getByLabel('Ghi chú / lý do xử lý', { exact: true }).fill('Hồ sơ mẫu cần bổ sung');
  await page.getByRole('button', { name: 'Tiếp tục', exact: true }).click();
  await page.route('**/api/bff/admin/companies/*/reject', route => route.fulfill({ status: 500, json: { error: { code: 'INTERNAL_ERROR' } } }));
  await page.getByRole('button', { name: 'Xác nhận', exact: true }).click();
  await expect(page.locator('.admin-access-panel [role=alert]')).toContainText('Không thể cập nhật doanh nghiệp');
  await page.getByRole('button', { name: 'Sửa nội dung', exact: true }).click();
  await expect(page.getByLabel('Ghi chú / lý do xử lý', { exact: true })).toHaveValue('Hồ sơ mẫu cần bổ sung');
  await page.unroute('**/api/bff/admin/companies/*/reject');
  await page.getByRole('button', { name: 'Tiếp tục', exact: true }).click(); await page.getByRole('button', { name: 'Xác nhận', exact: true }).click();
  await expect(page.locator('.admin-users-heading .admin-badge')).toHaveText('Đã từ chối');
  await expect(page.locator('.admin-company-rejection')).toContainText('Hồ sơ mẫu cần bổ sung');
});
