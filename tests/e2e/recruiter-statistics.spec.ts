import { expect, test } from './recruiter-fixture';
test('dashboard loads APIs, applies common filters and renders conversion rates and timeseries', async ({ page }, info) => {
  await page.goto('/recruiter/dashboard');
  await expect(page.getByRole('heading', { name: 'Tổng quan tuyển dụng' })).toHaveCount(1);
  await expect(page.locator('.stats-cards .stat-card').first()).toContainText('27');
  await page.locator('.dashboard-advanced > summary').click();
  await expect(page.locator('.stats-funnel tbody tr')).toHaveCount(4);
  await page.getByRole('button', { name: 'Bộ lọc thống kê', exact: true }).click();
  await page.getByLabel('Từ ngày', { exact: true }).fill('2026-10-01');
  await page.getByLabel('Đến ngày', { exact: true }).fill('2026-10-27');
  const response = page.waitForResponse(response => response.url().includes('/recruiter/stats/overview?') && response.url().includes('jobId='));
  await page.getByRole('combobox', { name: 'Tin tuyển dụng', exact: true }).click();
  await page.getByRole('option', { name: 'Fullstack Developer', exact: false }).first().click();
  expect((await response).status()).toBe(200);
  await expect(page.locator('.stats-funnel tbody tr')).toHaveCount(6);
  await page.getByRole('combobox', { name: 'Chỉ số thống kê' }).click();
  await page.getByRole('option', { name: 'Tin tạo mới', exact: true }).click();
  await expect(page.getByRole('img', { name: 'Tin tạo mới', exact: true })).toBeVisible();
  await page.locator('.stats-data-table summary').click();
  await expect(page.locator('.stats-data-table tbody tr').first()).toBeVisible();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: info.outputPath('dashboard-statistics-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 360, height: 800 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath('dashboard-statistics-mobile.png'), fullPage: true });
  await page.getByRole('button', { name: 'Xóa bộ lọc', exact: true }).click();
  await page.getByLabel('Từ ngày', { exact: true }).fill('2099-01-01');
  await page.getByLabel('Đến ngày', { exact: true }).fill('2099-01-31');
  await expect(page.locator('.stats-empty').first()).toBeVisible();
});
test('statistics panels offer retry and candidate education filter reaches the API and resets', async ({ page }) => {
  await page.route('**/api/bff/recruiter/stats/overview*', route => route.fulfill({ status: 500, json: { error: { code: 'INTERNAL_ERROR' } } }));
  await page.goto('/recruiter/dashboard');
  await expect(page.locator('.stats-error').first()).toContainText('Không thể tải thống kê');
  await page.unroute('**/api/bff/recruiter/stats/overview*');
  await page.getByRole('button', { name: 'Thử lại', exact: true }).first().click();
  await expect(page.locator('.stats-cards')).toBeVisible();
  await page.goto('/recruiter/candidates');
  await expect(page.locator('.candidate-card').first()).toBeVisible();
  const response = page.waitForResponse(response => response.url().includes('/api/bff/recruiter/applications?') && response.url().includes('educationLevel=college'));
  await page.getByRole('combobox', { name: 'Trình độ học vấn', exact: true }).click();
  await page.getByRole('option', { name: 'Cao đẳng', exact: true }).click();
  expect((await response).status()).toBe(200);
  await expect(page.locator('.candidate-card')).toHaveCount(7);
  await page.getByRole('button', { name: 'Xóa bộ lọc', exact: true }).first().click();
  await expect(page.getByRole('combobox', { name: 'Trình độ học vấn', exact: true })).toContainText('Tất cả trình độ');
  await expect(page.locator('.candidate-card')).toHaveCount(9);
});
