import { expect, test } from '@playwright/test';
import { z } from 'zod';
import { interviewSchema } from '@/lib/api/candidate-detail-schemas';
test('manage interviews through list, calendar, details and candidate timeline', async ({ page }, info) => {
  const applicationId = '00000000-0000-4000-9000-000000000003';
  const token = z.object({ csrfToken: z.string() }).parse(await (await page.request.get('/api/bff/auth/csrf')).json()).csrfToken;
  const create = async (day: string) => {
    const response = await page.request.post('/api/bff/recruiter/interviews', { headers: { 'X-CSRF-Token': token }, data: { applicationId, startTime: `2040-05-${day}T03:00:00Z`, endTime: `2040-05-${day}T04:00:00Z`, mode: 'offline', location: 'Văn phòng kiểm thử', sendInvitation: false } });
    expect(response.status()).toBe(201); return interviewSchema.parse(await response.json());
  };
  const interview = await create('10'); const other = await create('11');
  await page.goto('/recruiter/interviews');
  await expect(page.getByRole('heading', { name: 'Quản lý phỏng vấn' })).toBeVisible();
  await expect(page.locator('.interview-list-card')).toHaveCount(2);
  await page.getByRole('button', { name: 'Lịch tháng', exact: true }).click();
  await page.locator('input[type=month]').fill('2040-05');
  await expect(page.locator(`.interview-calendar a[href="/recruiter/interviews/${interview.id}"]`)).toBeVisible();
  await page.screenshot({ path: info.outputPath('interview-calendar-desktop.png'), fullPage: true });
  await page.locator(`.interview-calendar a[href="/recruiter/interviews/${interview.id}"]`).click();
  await page.getByRole('button', { name: 'Sửa lịch', exact: true }).click();
  const form = page.getByRole('form', { name: 'Sửa lịch' });
  await form.getByLabel('Bắt đầu (giờ Việt Nam)').fill('2040-05-12T10:00');
  await form.getByLabel('Kết thúc (giờ Việt Nam)').fill('2040-05-12T11:00');
  await form.getByRole('combobox', { name: 'Hình thức' }).click();
  await page.getByRole('option', { name: 'Trực tuyến', exact: true }).click();
  await form.getByLabel('Liên kết cuộc họp').fill('https://example.test/interview-room');
  await form.getByRole('button', { name: 'Lưu thay đổi', exact: true }).click();
  await expect(page.getByRole('status')).toHaveText('Đã cập nhật lịch phỏng vấn.');
  await expect(page.locator('.interview-detail-fields')).toContainText('Chờ phản hồi');
  await page.getByRole('button', { name: 'Gửi lại lời mời', exact: true }).click();
  await page.getByRole('button', { name: 'Xác nhận gửi', exact: true }).click();
  await expect(page.getByRole('status')).toHaveText('Đã gửi lời mời phỏng vấn.');
  await page.getByRole('button', { name: 'Ghi kết quả', exact: true }).click();
  const result = page.getByRole('form', { name: 'Ghi kết quả' });
  await result.getByRole('combobox', { name: 'Kết quả', exact: true }).click();
  await page.getByRole('option', { name: 'Đạt', exact: true }).click();
  await result.getByRole('textbox', { name: 'Nhận xét phỏng vấn' }).fill('Đáp ứng yêu cầu vòng phỏng vấn.');
  await result.getByRole('button', { name: 'Lưu kết quả', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Chỉnh sửa kết quả', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Sửa lịch', exact: true })).toHaveCount(0);
  await page.setViewportSize({ width: 360, height: 800 });
  await page.evaluate(() => window.scrollTo(0, 0));
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath('interview-detail-mobile.png'), fullPage: true });
  await page.goto(`/recruiter/interviews/${other.id}`);
  await page.getByRole('button', { name: 'Hủy lịch', exact: true }).click();
  await page.getByRole('button', { name: 'Xác nhận hủy lịch', exact: true }).click();
  await expect(page.getByRole('main').getByRole('alert')).toContainText('Thông tin chưa hợp lệ');
  await page.getByRole('textbox', { name: 'Lý do hủy', exact: true }).fill('Thay đổi kế hoạch phỏng vấn.');
  await page.getByRole('button', { name: 'Xác nhận hủy lịch', exact: true }).click();
  await expect(page.getByRole('status')).toHaveText('Đã hủy lịch phỏng vấn.');
  await page.reload();
  await expect(page.locator('.interview-cancel-reason')).toContainText('Thay đổi kế hoạch phỏng vấn.');
  await page.goto(`/recruiter/candidates/${applicationId}`);
  await expect(page.locator('.interview-results')).toContainText('Đáp ứng yêu cầu vòng phỏng vấn.');
});
test('interview list handles retry, empty filters and detail not found', async ({ page }) => {
  await page.route('**/api/bff/recruiter/interviews?*', route => route.fulfill({ status: 500, json: { error: { code: 'INTERNAL_ERROR' } } }));
  await page.goto('/recruiter/interviews');
  await expect(page.getByRole('main').getByRole('alert')).toContainText('Không thể tải hoặc lưu lịch');
  await page.unroute('**/api/bff/recruiter/interviews?*');
  await page.getByRole('button', { name: 'Thử lại', exact: true }).click();
  await expect(page.getByRole('main').getByRole('alert')).toHaveCount(0);
  await page.getByRole('combobox', { name: 'Trạng thái lời mời' }).click();
  await page.getByRole('option', { name: 'Đã từ chối', exact: true }).click();
  await expect(page.locator('.interview-empty')).toBeVisible();
  await page.goto('/recruiter/interviews/00000000-0000-4000-8000-000000000001');
  await expect(page.getByRole('main').getByRole('alert')).toContainText('Không tìm thấy buổi phỏng vấn.');
});
